// Writes src/wiro-media-model-ids.ts from the public Wiro model catalog, so
// editors can complete image, speech, transcription and video model IDs. It
// needs no API key and spends nothing.
//
//   node scripts/update-media-model-ids.mjs

import { writeFile } from 'node:fs/promises';

const CATALOG = 'https://api.wiro.ai/v1/Tool/List';

const GROUPS = [
  {
    type: 'WiroImageModelId',
    doc: 'Image models: text to image and image editing.',
    categories: ['text-to-image', 'image-to-image'],
  },
  { type: 'WiroSpeechModelId', doc: 'Text-to-speech models.', categories: ['text-to-speech'] },
  {
    type: 'WiroTranscriptionModelId',
    doc: 'Speech-to-text models.',
    categories: ['speech-to-text'],
  },
  {
    type: 'WiroVideoModelId',
    doc: 'Video models: text to video and image to video.',
    categories: ['text-to-video', 'image-to-video'],
  },
];

// Left out of the lists: models for adult content, live sessions that a
// one-shot call cannot drive, and models hidden from the catalog.
const HIDDEN = /uncensored|decensored|abliterated|obliterated|heretic|nsfw/i;

function listed(model) {
  const slug = `${model.cleanslugowner}/${model.cleanslugproject}`;
  if (HIDDEN.test(`${slug} ${model.title ?? ''}`)) return false;
  if (String(model.noindex) === '1') return false;
  const categories = (model.categories ?? []).map((category) => String(category).toLowerCase());
  if (categories.some((category) => category.includes('realtime')) || slug.includes('realtime')) {
    return false;
  }
  return !JSON.stringify(model.dynamicprice ?? '').includes('cp-realtimeturn');
}

async function modelsIn(category) {
  const response = await fetch(CATALOG, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json', 'User-Agent': 'wiro-llm-model-ids' },
    body: JSON.stringify({
      start: '0',
      limit: '1000',
      search: '',
      categories: [category],
      sort: 'relevance',
      hideworkflows: true,
      summary: true,
    }),
  });
  const body = await response.json();
  if (!response.ok || body.result === false) {
    throw new Error(`The catalog answered ${response.status} for ${category}.`);
  }
  return body.tool ?? [];
}

const sections = [];
for (const group of GROUPS) {
  const ids = new Set();
  for (const category of group.categories) {
    for (const model of await modelsIn(category)) {
      if (listed(model)) ids.add(`${model.cleanslugowner}/${model.cleanslugproject}`);
    }
  }
  const lines = [...ids].sort().map((id) => `  | '${id}'`);
  sections.push(
    `/** ${group.doc} */\nexport type ${group.type} =\n${lines.join('\n')}\n  | (string & {});`,
  );
  console.log(`${group.type}: ${ids.size} models`);
}

const header = `// Generated by scripts/update-media-model-ids.mjs from the Wiro model
// catalog (https://wiro.ai/models). The lists give editor autocomplete; any
// other owner/model ID works too, so models added later need no update.
`;
await writeFile(
  new URL('../src/wiro-media-model-ids.ts', import.meta.url),
  `${header}\n${sections.join('\n\n')}\n`,
);
